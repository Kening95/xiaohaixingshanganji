/** 按科目筛选节目 */
export function episodesBySubject(subject) {
  return EPISODES.filter((e) => e.subject === subject)
}

/** 按日期取种子（同一天所有人听到的"每日推送"一致） */
function daySeed() {
  return new Date().toLocaleDateString('sv-SE').replace(/-/g, '')
}

/** 简单可复现的伪随机：同一种子同一顺序（每日推送模式用） */
function seededShuffle(list, seed) {
  const copy = [...list]
  let s = Number(seed) || 1
  for (let i = copy.length - 1; i > 0; i--) {
    s = (s * 9301 + 49297) % 233280
    const j = s % (i + 1);
    [copy[i], copy[j]] = [copy[j], copy[i]]
  }
  return copy
}

/** 每日推送：按日期种子抽 3 条，全站用户同一天听同一组 */
export function pickDailyEpisodes() {
  return seededShuffle(EPISODES, daySeed()).slice(0, 3)
}

/** 薄弱定向：根据传入的薄弱科目列表选节目，最多 5 条 */
export function pickWeakEpisodes(weakSubjects) {
  const picked = []
  for (const subject of weakSubjects) {
    picked.push(...episodesBySubject(subject))
  }
  return picked.slice(0, 5)
}

/** 全板块循环：所有节目按日期种子洗牌后完整循环 */
export function pickLoopEpisodes() {
  return seededShuffle(EPISODES, daySeed())
}
